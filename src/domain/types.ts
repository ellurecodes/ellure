export const EarningClassificationEnum = z.enum(['verified', 'uncertain']);
export type EarningClassification = z.infer<typeof EarningClassificationEnum>;

export const ConfidenceLevelEnum = z.enum(['low', 'medium', 'high']);
export type ConfidenceLevel = z.infer<typeof ConfidenceLevelEnum>;

export interface ClassificationAudit {
  fromClassification: EarningClassification;
  toClassification: EarningClassification;
  timestamp: string;
  reason: string;
}

export const EarningRecordSchema = z.object({
  id: z.string().min(1),
  userId: z.string().optional(),
  platformId: z.string().min(1, 'Platform is required'),
  date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Date must be YYYY-MM-DD'),
  title: z.string().min(1, 'Task or task title is required'),
  amountMinorUnits: z.number().int().positive('Amount must be positive'),
  currency: z.string().default('INR'),
  exchangeRateToInr: z.number().positive().default(1),
  exchangeRateDate: z.string().default(''),
  inrAmountPaise: z.number().int().positive(),
  classification: EarningClassificationEnum,
  confidenceLevel: ConfidenceLevelEnum.optional(),
  reasonForUncertainty: z.string().optional(),
  reviewDate: z.string().optional(),
  evidenceNote: z.string().optional(),
  allocatedToWithdrawalPaise: z.number().int().nonnegative().optional(),
  auditTrail: z.array(z.custom<ClassificationAudit>()).optional(),
  createdAt: z.string(),
  updatedAt: z.string(),
  deletedAt: z.string().nullable().optional(),
}).refine(data => {
  if (data.classification === 'uncertain') {
    return !!data.confidenceLevel && !!data.reasonForUncertainty && !!data.reviewDate;
  }
  return true;
}, {
  message: 'Uncertain earnings require confidence level, reason, and review date',
  path: ['reasonForUncertainty'],
});
export type EarningRecord = z.infer<typeof EarningRecordSchema>;

