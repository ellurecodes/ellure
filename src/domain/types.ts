export const TransactionTypeEnum = z.enum([
  'income',
  'expense',
  'transfer',
  'earning_payout',
  'loan_given',
  'loan_received',
  'loan_repayment_in',
  'loan_repayment_out',
  'adjustment',
]);
export type TransactionType = z.infer<typeof TransactionTypeEnum>;

const BaseTransactionSchema = z.object({
  id: z.string().min(1),
  userId: z.string().optional(),
  date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Date must be YYYY-MM-DD'),
  title: z.string().min(1, 'Title is required'),
  notes: z.string().optional(),
  tags: z.array(z.string()).optional(),
  createdAt: z.string(), // UTC ISO
  updatedAt: z.string(), // UTC ISO
  deletedAt: z.string().nullable().optional(),
  isAutoGenerated: z.boolean().optional(),
  recurringScheduleId: z.string().optional(),
});

export const IncomeTransactionSchema = BaseTransactionSchema.extend({
  type: z.literal('income'),
  accountId: z.string().min(1, 'Account is required'),
  amountPaise: z.number().int().positive('Amount must be positive'),
  category: z.string().min(1, 'Category is required'),
});

export const ExpenseTransactionSchema = BaseTransactionSchema.extend({
  type: z.literal('expense'),
  accountId: z.string().min(1, 'Account is required'),
  amountPaise: z.number().int().positive('Amount must be positive'),
  category: z.string().min(1, 'Category is required'),
});

export const TransferTransactionSchema = BaseTransactionSchema.extend({
  type: z.literal('transfer'),
  fromAccountId: z.string().min(1, 'Source account is required'),
  toAccountId: z.string().min(1, 'Destination account is required'),
  amountPaise: z.number().int().positive('Amount must be positive'),
  feePaise: z.number().int().nonnegative().default(0),
  linkedFeeExpenseId: z.string().optional(),
}).refine(data => data.fromAccountId !== data.toAccountId, {
  message: 'Source and destination accounts must be different',
  path: ['toAccountId'],
});

export const EarningPayoutTransactionSchema = BaseTransactionSchema.extend({
  type: z.literal('earning_payout'),
  accountId: z.string().min(1, 'Account is required'),
  amountPaise: z.number().int().positive('Amount must be positive'),
  platformId: z.string().min(1, 'Platform is required'),
  withdrawalId: z.string().optional(),
  grossPaise: z.number().int().positive(),
  feePaise: z.number().int().nonnegative().default(0),
  allocatedRecordIds: z.array(z.string()).default([]),
});

export const LoanTransactionSchema = BaseTransactionSchema.extend({
  type: z.enum(['loan_given', 'loan_received', 'loan_repayment_in', 'loan_repayment_out']),
  accountId: z.string().min(1, 'Account is required'),
  amountPaise: z.number().int().positive('Amount must be positive'),
  personName: z.string().min(1, 'Person name is required'),
  dueDate: z.string().regex(/^\d{4}-\d{2}-\d{2}$/).optional(),
  linkedLoanId: z.string().optional(),
});

export const AdjustmentTransactionSchema = BaseTransactionSchema.extend({
  type: z.literal('adjustment'),
  accountId: z.string().min(1, 'Account is required'),
  // delta can be positive or negative
  deltaPaise: z.number().int().refine(val => val !== 0, 'Adjustment delta cannot be zero'),
  statedBalancePaise: z.number().int(),
  computedBalancePaise: z.number().int(),
  reason: z.string().min(1, 'Reconciliation reason is required'),
});

export const TransactionSchema = z.discriminatedUnion('type', [
  IncomeTransactionSchema,
  ExpenseTransactionSchema,
  TransferTransactionSchema,
  EarningPayoutTransactionSchema,
  LoanTransactionSchema,
  AdjustmentTransactionSchema,
]);

export type Transaction = z.infer<typeof TransactionSchema>;
export type IncomeTransaction = z.infer<typeof IncomeTransactionSchema>;
export type ExpenseTransaction = z.infer<typeof ExpenseTransactionSchema>;
export type TransferTransaction = z.infer<typeof TransferTransactionSchema>;
export type EarningPayoutTransaction = z.infer<typeof EarningPayoutTransactionSchema>;
export type LoanTransaction = z.infer<typeof LoanTransactionSchema>;
export type AdjustmentTransaction = z.infer<typeof AdjustmentTransactionSchema>;

