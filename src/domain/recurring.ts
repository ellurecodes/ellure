import { RecurringTransaction, Transaction, ExpenseTransaction, IncomeTransaction } from './types';

/**
 * Computes next due date string (YYYY-MM-DD) based on schedule frequency.
 */
export function calculateNextDueDate(
  currentDateStr: string,
  frequency: 'daily' | 'weekly' | 'monthly' | 'yearly'
): string {
  const d = new Date(currentDateStr + 'T12:00:00Z');
  switch (frequency) {
    case 'daily':
      d.setUTCDate(d.getUTCDate() + 1);
      break;
    case 'weekly':
      d.setUTCDate(d.getUTCDate() + 7);
      break;
    case 'monthly':
      d.setUTCMonth(d.getUTCMonth() + 1);
      break;
    case 'yearly':
      d.setUTCFullYear(d.getUTCFullYear() + 1);
      break;
  }
  return d.toISOString().slice(0, 10);
}

/**
 * Generates due instances for recurring schedules up to today.
 * Pure and idempotent: checks existing transactions by recurringScheduleId + date.
 * Never creates duplicate records even if invoked multiple times.
 */
export function generateDueRecurringTransactions(
  schedules: RecurringTransaction[],
  existingTransactions: Transaction[],
  todayStr: string = new Date().toISOString().slice(0, 10)
): {
  newTransactions: (IncomeTransaction | ExpenseTransaction)[];
  updatedSchedules: RecurringTransaction[];
} {
  const newTransactions: (IncomeTransaction | ExpenseTransaction)[] = [];
  const updatedSchedules: RecurringTransaction[] = [];

  // Build a lookup set of existing generated occurrences: `${recurringScheduleId}:${date}`
  const generatedSet = new Set<string>();
  for (const tx of existingTransactions) {
    if (tx.recurringScheduleId) {
      generatedSet.add(`${tx.recurringScheduleId}:${tx.date}`);
    }
  }

  const now = new Date().toISOString();

  for (const schedule of schedules) {
    if (!schedule.isActive || schedule.deletedAt) continue;

    let cursorDate = schedule.nextDueDate;
    let scheduleUpdated = false;
    let updatedSchedule = { ...schedule };

    // Advance cursor while due date <= today
    while (cursorDate <= todayStr) {
      const key = `${schedule.id}:${cursorDate}`;
      if (!generatedSet.has(key)) {
        // Generate new instance
        const baseTx = {
          id: `rec_${schedule.id}_${cursorDate}_${Math.random().toString(36).substring(2, 7)}`,
          date: cursorDate,
          title: `${schedule.title} (Recurring)`,
          notes: schedule.notes || 'Auto-generated recurring transaction',
          tags: ['recurring'],
          createdAt: now,
          updatedAt: now,
          deletedAt: null,
          isAutoGenerated: true,
          recurringScheduleId: schedule.id,
        };

        if (schedule.type === 'expense') {
          const exp: ExpenseTransaction = {
            ...baseTx,
            type: 'expense',
            accountId: schedule.accountId,
            amountPaise: schedule.amountPaise,
            category: schedule.category,
          };
          newTransactions.push(exp);
        } else {
          const inc: IncomeTransaction = {
            ...baseTx,
            type: 'income',
            accountId: schedule.accountId,
            amountPaise: schedule.amountPaise,
            category: schedule.category,
          };
          newTransactions.push(inc);
        }

        generatedSet.add(key);
      }

      // Move to next occurrence
      cursorDate = calculateNextDueDate(cursorDate, schedule.frequency);
      scheduleUpdated = true;
    }

    if (scheduleUpdated) {
      updatedSchedule.nextDueDate = cursorDate;
      updatedSchedule.lastGeneratedDate = todayStr;
      updatedSchedule.updatedAt = now;
      updatedSchedules.push(updatedSchedule);
    }
  }

  return { newTransactions, updatedSchedules };
}
