import Dexie, { type Table } from 'dexie';
import {
  User,
  Account,
  Transaction,
  Platform,
  EarningRecord,
  Withdrawal,
  Budget,
  SavingsGoal,
  RecurringTransaction,
  Subject,
  AcademicTask,
  Habit,
  HabitLog,
  FitnessMetricLog,
  Goal,
  UserSettings,
} from '../domain/types';

export class LifeOSDatabase extends Dexie {
  users!: Table<User, string>;
  accounts!: Table<Account, string>;
  transactions!: Table<Transaction, string>;
  platforms!: Table<Platform, string>;
  earningRecords!: Table<EarningRecord, string>;
  withdrawals!: Table<Withdrawal, string>;
  budgets!: Table<Budget, string>;
  savingsGoals!: Table<SavingsGoal, string>;
  recurringTransactions!: Table<RecurringTransaction, string>;
  subjects!: Table<Subject, string>;
  academicTasks!: Table<AcademicTask, string>;
  habits!: Table<Habit, string>;
  habitLogs!: Table<HabitLog, string>;
  fitnessMetricLogs!: Table<FitnessMetricLog, string>;
  goals!: Table<Goal, string>;
  settings!: Table<UserSettings, string>;

  constructor() {
    super('LifeOS_DB');

    // Schema version 1
    this.version(1).stores({
      accounts: 'id, name, type, isArchived, isExcludedFromSpendable, deletedAt, createdAt',
      transactions: 'id, type, date, accountId, category, isAutoGenerated, recurringScheduleId, deletedAt, createdAt',
      platforms: 'id, name, category, trustStatus, deletedAt, createdAt',
      earningRecords: 'id, platformId, date, classification, deletedAt, createdAt',
      withdrawals: 'id, platformId, status, requestedDate, deletedAt, createdAt',
      budgets: 'id, [month+category], month, category',
      savingsGoals: 'id, linkedAccountId, isCompleted, deletedAt, createdAt',
      recurringTransactions: 'id, nextDueDate, isActive, deletedAt, createdAt',
      subjects: 'id, code, isArchived, createdAt',
      academicTasks: 'id, subjectId, dueDate, priority, status, deletedAt, createdAt',
      habits: 'id, isArchived, createdAt',
      habitLogs: 'id, [habitId+date], habitId, date, completed',
      fitnessMetricLogs: 'id, date',
      goals: 'id, category, targetDate, status, deletedAt, createdAt',
      settings: 'id',
    });

    // Schema version 2: Multi-user support with user role & account status
    this.version(2).stores({
      users: 'id, username, role, status, createdAt',
      accounts: 'id, userId, name, type, isArchived, isExcludedFromSpendable, deletedAt, createdAt',
      transactions: 'id, userId, type, date, accountId, category, isAutoGenerated, recurringScheduleId, deletedAt, createdAt',
      platforms: 'id, userId, name, category, trustStatus, deletedAt, createdAt',
      earningRecords: 'id, userId, platformId, date, classification, deletedAt, createdAt',
      withdrawals: 'id, userId, platformId, status, requestedDate, deletedAt, createdAt',
      budgets: 'id, userId, [month+category], month, category',
      savingsGoals: 'id, userId, linkedAccountId, isCompleted, deletedAt, createdAt',
      recurringTransactions: 'id, userId, nextDueDate, isActive, deletedAt, createdAt',
      subjects: 'id, userId, code, isArchived, createdAt',
      academicTasks: 'id, userId, subjectId, dueDate, priority, status, deletedAt, createdAt',
      habits: 'id, userId, isArchived, createdAt',
      habitLogs: 'id, userId, [habitId+date], habitId, date, completed',
      fitnessMetricLogs: 'id, userId, date',
      goals: 'id, userId, category, targetDate, status, deletedAt, createdAt',
      settings: 'id, userId',
    });
  }
}

export const db = new LifeOSDatabase();
